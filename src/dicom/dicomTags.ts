export function formatDicomTag(tagKey: string): string {
  const clean = tagKey.startsWith('x') ? tagKey.slice(1) : tagKey;
  if (clean.length === 8) {
    return `(${clean.slice(0, 4).toUpperCase()},${clean.slice(4, 8).toUpperCase()})`;
  }
  return tagKey;
}
